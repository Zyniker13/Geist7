import Foundation
import RSCore

/// INV-5 (RS-P1.4): on random positions, an expectiminimax probe that uses
/// the ENGINE's own move generation (UrMoveGenerator + capture semantics)
/// with the solved table as the leaf evaluator must never find a line that
/// beats the table's value for the position. This is the bridge check that
/// the rules engine and the solver agree on the rules: entry (R-3), bear-off
/// (R-7), captures (R-5, R-20), and rosette extra rolls (R-6, R-19).
enum Inv5Check {

    /// Builds the engine's piece list from a solver position. Player 0 of the
    /// position is the rolling player, so it maps to `.player0`.
    static func enginePieces(of position: UrPosition, pieces: Int) -> [Piece] {
        var piecesOut: [Piece] = []
        func append(_ owner: PlayerID, _ step: Int) {
            var piece = Piece.making(id: piecesOut.count, owner: owner)
            piece.position = step
            piecesOut.append(piece)
        }
        for index in 0..<8 {
            switch position.sharedDigit(index) {
            case 1: append(.player0, UrRanking.sharedStart + index)
            case 2: append(.player1, UrRanking.sharedStart + index)
            default: break
            }
        }
        // Private bitmaps: bits 0–3 are steps 0–3, bits 4–5 are steps 12–13.
        let privateSteps = [0, 1, 2, 3, 12, 13]
        for (bit, step) in zip(privateSteps.indices, privateSteps) {
            if position.private0 & (1 << UInt32(bit)) != 0 { append(.player0, step) }
            if position.private1 & (1 << UInt32(bit)) != 0 { append(.player1, step) }
        }
        for _ in 0..<position.hand0 { append(.player0, -1) }
        for _ in 0..<position.hand1 { append(.player1, -1) }
        let onBoard0 = position.privateCount0 + position.sharedCount0
        let onBoard1 = position.privateCount1 + position.sharedCount1
        for _ in 0..<(pieces - position.hand0 - onBoard0) { append(.player0, -2) }
        for _ in 0..<(pieces - position.hand1 - onBoard1) { append(.player1, -2) }
        return piecesOut
    }

    /// Recovers the solver position from an engine piece list.
    static func tuple(from pieces: [Piece]) -> UrPosition {
        var shared: UInt32 = 0
        var private0: UInt32 = 0
        var private1: UInt32 = 0
        var hand0 = 0
        var hand1 = 0
        for piece in pieces {
            switch piece.position {
            case -1:
                if piece.owner == .player0 { hand0 += 1 } else { hand1 += 1 }
            case -2:
                break
            case let step:
                if step >= UrRanking.sharedStart && step < 12 {
                    let digit: UInt32 = piece.owner == .player0 ? 1 : 2
                    shared |= digit << UInt32((step - UrRanking.sharedStart) * 2)
                } else {
                    let bit: UInt32 = step < 4 ? UInt32(step) : UInt32(step - 12 + 4)
                    if piece.owner == .player0 {
                        private0 |= 1 << bit
                    } else {
                        private1 |= 1 << bit
                    }
                }
            }
        }
        return UrPosition(
            shared: shared, private0: private0, private1: private1, hand0: hand0, hand1: hand1)
    }

    /// Applies one engine move with capture semantics and returns the next
    /// piece list. The move is assumed legal (generated by UrMoveGenerator);
    /// `move.piece` is the global piece id assigned in `enginePieces`.
    static func apply(_ move: Move, to pieces: [Piece], player: PlayerID) -> [Piece] {
        var next = pieces
        guard let index = next.firstIndex(where: { $0.id == move.piece }) else {
            fatalError("INV-5: move references an unknown piece")
        }
        if move.destination == -1 {
            next[index].position = -2
            return next
        }
        next[index].position = move.destination
        // On a shared square any occupant must be an opponent (UrMoveGenerator
        // rejects own-piece landings and safe-rosette captures), so landing
        // captures it back to hand (R-20).
        if move.destination >= UrRanking.sharedStart && move.destination < 12 {
            if let victim = next.firstIndex(where: {
                $0.owner != player && $0.position == move.destination
            }) {
                next[victim].position = -1
            }
        }
        return next
    }

    /// Runs the INV-5 probe over `samples` random positions drawn from the
    /// full tuple space with `rng`. Returns (checked, worst deviation, first
    /// failing description) — the deviation compares the engine-derived
    /// expectiminimax value against the solver's stored value.
    static func run(
        solver: UrSolver, values: [Double], samples: Int, rng: inout SeededRNG
    ) -> (checked: Int, maxDelta: Double, failure: String?) {
        let ranking = solver.ranking
        let pieces = solver.pieces
        let track = RuleSet.finkel.makeTrack()
        let generator = UrMoveGenerator()

        // Enumerate the tuple space once and sample uniformly from it.
        var tuples: [UrPosition] = []
        tuples.reserveCapacity(ranking.totalPositions)
        for s in 0..<UrRanking.sharedPatterns {
            let n0 = ranking.sharedCount0(s)
            let n1 = ranking.sharedCount1(s)
            let packed = UrPosition.base3ToPacked[s]
            for priv0 in 0..<64 {
                let on0 = n0 + priv0.nonzeroBitCount
                guard on0 <= pieces else { continue }
                for priv1 in 0..<64 {
                    let on1 = n1 + priv1.nonzeroBitCount
                    guard on1 <= pieces else { continue }
                    for layer in 0..<ranking.layerCount {
                        guard let bounds = ranking.handPairBounds(on0, on1, layer) else { continue }
                        let k = 2 * pieces - on0 - on1 - layer
                        for hand0 in bounds.low...bounds.high {
                            tuples.append(
                                UrPosition(
                                    shared: packed, private0: UInt32(priv0),
                                    private1: UInt32(priv1),
                                    hand0: hand0, hand1: k - hand0))
                        }
                    }
                }
            }
        }

        var checked = 0
        var maxDelta = 0.0
        var failure: String?
        var draws = 0
        while checked < samples && draws < samples * 4 && draws < tuples.count * 4 {
            draws += 1
            let position = tuples[Int(rng.next() % UInt64(tuples.count))]
            // Skip decided positions: a side with no hand and no board pieces has
            // already finished, the value is a forced boundary value, and the
            // engine has nothing to probe (the published tables omit these too).
            if position.hand0 + position.privateCount0 + position.sharedCount0 == 0 {
                continue
            }
            if position.hand1 + position.privateCount1 + position.sharedCount1 == 0 {
                continue
            }

            let enginePiecesList = enginePieces(of: position, pieces: pieces)
            let stored = values[ranking.index(of: position)]
            var engineValue = 0.0
            for roll in 0...4 {
                let weight =
                    Double(UrRanking.diceWeights[roll])
                    / Double(UrRanking.diceDenominator)
                if roll == 0 {
                    engineValue +=
                        weight
                        * (1.0 - values[ranking.index(of: ranking.mirrored(position))])
                    continue
                }
                let moves = generator.legalMoves(
                    for: .player0, amount: roll, pieces: enginePiecesList, track: track,
                    rules: .finkel, unsafeRosettesActive: false, allowEntry: true
                )
                var best = -Double.infinity
                for move in moves {
                    let next = apply(move, to: enginePiecesList, player: .player0)
                    let successor = tuple(from: next)
                    let value: Double
                    if move.destination == -1 {
                        let remaining = next.filter { $0.owner == .player0 && !$0.isBorneOff }.count
                        value =
                            remaining == 0
                            ? 1.0
                            : 1.0 - values[ranking.index(of: ranking.mirrored(successor))]
                    } else if RuleSet.finkel.rosettes.contains(move.destination) {
                        value = values[ranking.index(of: successor)]
                    } else {
                        value = 1.0 - values[ranking.index(of: ranking.mirrored(successor))]
                    }
                    if value > best { best = value }
                }
                if best == -Double.infinity {
                    best = 1.0 - values[ranking.index(of: ranking.mirrored(position))]
                }
                engineValue += weight * best
            }
            let delta = abs(engineValue - stored)
            if delta > maxDelta { maxDelta = delta }
            if delta > 1e-6 && failure == nil {
                var digits = ""
                for i in 0..<8 { digits += String(position.sharedDigit(i)) }
                failure =
                    "shared=\(digits) priv0=\(position.private0) priv1=\(position.private1) "
                    + "h0=\(position.hand0) h1=\(position.hand1) engine=\(engineValue) "
                    + "solver=\(stored) Δ=\(delta)"
            }
            checked += 1
        }
        return (checked, maxDelta, failure)
    }
}
