#!/bin/bash
# todo-map — generate docs/TODO_MAP.md from "// TODO(<ID>):" comments.
# Every TODO carries a task ID from the game roadmap (e.g. RS-P6.2).
# Grouped by package; a TODO without an ID fails the script (exit 1).

set -euo pipefail
cd "$(dirname "$0")/.."

mapfile="docs/TODO_MAP.md"
mkdir -p docs

matches=$(grep -rn --include='*.swift' --include='*.sh' --exclude-dir=.build \
  -E 'TODO\(([A-Za-z0-9._-]+)\)' Packages App Tools 2>/dev/null || true)

missing=$(grep -rn --include='*.swift' --include='*.sh' --exclude-dir=.build \
  -E '(//|#+) *TODO[^(<]*$' Packages App Tools 2>/dev/null || true)

{
  echo "# Rosette — TODO Map"
  echo
  echo "Generated by \`make todo\` (Tools/todo-map.sh) from \`// TODO(<ID>):\` comments."
  echo "IDs reference the game roadmap task list."
  echo
  if [ -z "$matches" ]; then
    echo "No TODO comments yet."
  else
    echo "$matches" | sort | awk -F: '{ pkg=$1; sub("Packages/","",pkg); sub("/.*","",pkg); if (pkg !~ /^(App|Tools)$/) pkg="Packages/" pkg; print pkg "\t" $0 }' \
      | awk -F'\t' '{ if ($1 != last) { print "\n## " $1; last=$1 } sub(/^[^\t]*\t/, ""); print "- " $0 }'
  fi
} > "$mapfile"

if [ -n "$missing" ]; then
  echo "ERROR: TODO comments without a task ID:" >&2
  echo "$missing" >&2
  exit 1
fi

echo "Wrote $mapfile"
